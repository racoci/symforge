/**
 * Interactive Visual Variation Gallery - Type Definitions.
 *
 * Defines props, state, and interaction interfaces for the slide-out
 * procedural variation gallery drawer and individual variation candidate cards.
 */

import type { PunctureResult } from '../../core/generator/types';
import type { CurriculumLevel, VariationCandidate } from '../../core/pcfg/types';

/**
 * Filter level options: All curriculum levels ('ALL') or specific level ('L1'..'L5').
 */
export type GalleryFilterLevel = CurriculumLevel | 'ALL';

/**
 * Props for the top-level VariationGallery sliding drawer component.
 */
export interface VariationGalleryProps {
  /** Whether the gallery drawer is currently visible */
  isOpen: boolean;
  /** Callback fired when user closes the gallery drawer */
  onClose: () => void;
  /** List of candidate variations generated by PCFG/PHOG sampler */
  candidates: VariationCandidate[];
  /** Whether variation generation is currently in progress */
  isLoading: boolean;
  /** Error message string if generation failed, or null if healthy */
  error: string | null;
  /** The hole puncturing context for which variations were sampled */
  punctureResult: PunctureResult | null;
  /** Currently active curriculum level filter */
  selectedLevel: GalleryFilterLevel;
  /** Callback fired when user selects a different level filter tab */
  onSelectLevel: (lvl: GalleryFilterLevel) => void;
  /** Callback fired when user requests regeneration of variations */
  onRegenerate: () => void;
  /** Callback fired when user clicks 'Apply to Editor' on a candidate card */
  onInjectVariation: (candidate: VariationCandidate) => void;
}

/**
 * Props for an individual candidate variation card.
 */
export interface VariationCardProps {
  /** Candidate variation data */
  candidate: VariationCandidate;
  /** Callback fired when user selects this variation to inject into the editor */
  onApply: (candidate: VariationCandidate) => void;
  /** Optional flag indicating whether this candidate is currently being applied */
  isApplying?: boolean;
}
